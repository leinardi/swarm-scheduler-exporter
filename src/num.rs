//! The one numeric conversion the collectors share.

/// An integer as a gauge value. Above 2^53 the rounding is what an `as f64` conversion gives,
/// which is the value Go writes.
#[expect(
    clippy::cast_precision_loss,
    reason = "above 2^53 the rounding is the value the Go exporter wrote"
)]
pub(crate) fn from_int(value: impl Into<i128>) -> f64 {
    value.into() as f64
}
